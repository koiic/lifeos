#!/usr/bin/env python3
"""Generate web/src/ui/tokens.css and web/src/ui/tokens.ts from design/tokens.json.

Usage:
  python3 scripts/build_tokens.py          # write the generated files
  python3 scripts/build_tokens.py --check  # exit 1 if the generated files are stale

Plan section 5.1. Stdlib only.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "design" / "tokens.json"
CSS_OUT = ROOT / "web" / "src" / "ui" / "tokens.css"
TS_OUT = ROOT / "web" / "src" / "ui" / "tokens.ts"
HEADER = "GENERATED by scripts/build_tokens.py from design/tokens.json. Do not edit by hand."


def theme_vars(theme: dict) -> list[tuple[str, str]]:
    out = [(name, value) for name, value in theme["color"].items()]
    out += [(f"font-{k}", v) for k, v in theme["font"].items()]
    out += [(f"font-weight-{k}", v) for k, v in theme["font-weight"].items()]
    # CR-005: per-theme font-variation-settings (Fraunces "SOFT" 100 in Night Garden).
    out += [(f"font-variation-{k}", v) for k, v in theme.get("font-variation", {}).items()]
    return out


def shared_vars(shared: dict) -> list[tuple[str, str]]:
    out: list[tuple[str, str]] = []
    for group, values in shared.items():
        for k, v in values.items():
            out.append((f"{group}-{k}", v))
    return out


def block(selector: str, pairs: list[tuple[str, str]], indent: str = "  ") -> str:
    body = "\n".join(f"{indent}--{k}: {v};" for k, v in pairs)
    return f"{selector} {{\n{body}\n}}"


def render(tokens: dict) -> tuple[str, str]:
    light = theme_vars(tokens["themes"]["light"])
    dark = theme_vars(tokens["themes"]["dark"])
    shared = shared_vars(tokens["shared"])
    dark_body = "\n".join(f"    --{k}: {v};" for k, v in dark)
    css = "\n\n".join([
        f"/* {HEADER} */",
        block(":root", shared + light),
        block(':root[data-theme="dark"]', dark),
        "@media (prefers-color-scheme: dark) {\n"
        f'  :root:not([data-theme="light"]) {{\n{dark_body}\n  }}\n}}',
        "@media (prefers-reduced-motion: reduce) {\n"
        "  :root {\n    --motion-duration-fast: 0ms;\n    --motion-duration-base: 0ms;\n"
        "    --motion-duration-ring: 0ms;\n  }\n}",
    ]) + "\n"
    names = sorted({k for k, _ in light} | {k for k, _ in dark} | {k for k, _ in shared})
    ts = (
        f"// {HEADER}\n\n"
        "export const tokenNames = [\n"
        + "".join(f"  '{n}',\n" for n in names)
        + "] as const;\n\n"
        "export type TokenName = (typeof tokenNames)[number];\n\n"
        "/** Use in style objects only for CSS custom properties, e.g. token('accent'). */\n"
        "export const token = (name: TokenName): string => `var(--${name})`;\n\n"
        "export const themes = { light: 'Sorbet', dark: 'Night Garden' } as const;\n"
    )
    return css, ts


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args()
    css, ts = render(json.loads(SRC.read_text()))
    if args.check:
        stale = [p for p, c in ((CSS_OUT, css), (TS_OUT, ts)) if not p.exists() or p.read_text() != c]
        if stale:
            for p in stale:
                print(f"STALE: {p.relative_to(ROOT)} (run: python3 scripts/build_tokens.py)", file=sys.stderr)
            return 1
        print("tokens: generated files are current")
        return 0
    CSS_OUT.parent.mkdir(parents=True, exist_ok=True)
    CSS_OUT.write_text(css)
    TS_OUT.write_text(ts)
    print(f"wrote {CSS_OUT.relative_to(ROOT)} and {TS_OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
